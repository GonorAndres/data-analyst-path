export function useABText() {
  const { locale } = usePreferences()
  const labels: Record<string, string> = { conversion_rate: 'Conversion Rate', revenue_per_user: 'Revenue per user', session_duration_sec: 'Session duration (s)' }
  return (source: string) => {
    const text = labels[source] ?? source
    if (locale !== 'es') return text
    const probability = /^(Treatment|Control) wins with ([\d.]+%) probability$/.exec(text)
    if (probability) return `${probability[1] === 'Treatment' ? 'Tratamiento' : 'Control'} gana con una probabilidad del ${probability[2]}`
    return spanish[text] ?? text
  }
}
